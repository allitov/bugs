package io.allitov.bugs.model

import androidx.annotation.DrawableRes

/**
 * Бонус на игровом поле. При нажатии включает режим наклона: на время действия
 * движение жуков учитывает угол наклона телефона, и жуки скатываются в сторону
 * наклона (например, к углу экрана).
 *
 * Позиция [x], [y] и размер [size] хранятся в логической системе координат
 * игрового поля и не зависят от пикселей конкретного устройства.
 *
 * @property id       уникальный идентификатор бонуса
 * @property x        координата центра бонуса по горизонтали в логических единицах
 * @property y        координата центра бонуса по вертикали в логических единицах
 * @property size     радиус бонуса в логических единицах
 * @property imageRes визуальный ресурс бонуса
 */
data class Bonus(
    val id: Long,
    val x: Float,
    val y: Float,
    val size: Float,
    @DrawableRes val imageRes: Int
)
